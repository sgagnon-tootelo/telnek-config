    lang = normalize_primary_language(client.get("primary_language"))
    tz = client.get("timezone")
    if tz and str(tz).strip() in _IANA_SET:
        return str(tz).strip()
    if tz and str(tz).strip():
        return str(tz).strip()
    return DEFAULT_TIMEZONE_BY_LANG.get(lang, "America/Montreal")