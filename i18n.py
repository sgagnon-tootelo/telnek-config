def get_ui_lang(session_state) -> str:
    lang = session_state.get("ui_lang", "fr")
    return lang if lang in TRANSLATIONS else "fr"


def t(key: str, session_state, **kwargs) -> str:
    lang = get_ui_lang(session_state)
    text = TRANSLATIONS[lang].get(key) or TRANSLATIONS["fr"].get(key, key)
    return text.format(**kwargs) if kwargs else text


def primary_language_label(value: str, ui_lang: str) -> str:
    for opt in PRIMARY_LANGUAGES:
        if opt["value"] == value:
            return opt[f"label_{ui_lang}"]
    return value


def timezone_label(iana: str, ui_lang: str) -> str:
    for opt in TIMEZONE_OPTIONS:
        if opt["iana"] == iana:
            return opt[f"label_{ui_lang}"]
    return iana


def normalize_primary_language(value: str | None) -> str:
    if not value:
        return "fr-CA"
    normalized = str(value).strip().lower().replace("_", "-")
    if normalized in ("en", "en-us"):
        return "en-US"
    return "fr-CA"


def resolve_client_timezone(client: dict) -> str:
    lang = normalize_primary_language(client.get("primary_language"))
    tz = client.get("timezone")
    if tz and str(tz).strip() in _IANA_SET:
        return str(tz).strip()
    if tz and str(tz).strip():
        return str(tz).strip()
    return DEFAULT_TIMEZONE_BY_LANG.get(lang, "America/Montreal")